import { test, expect } from '@playwright/test';
import { practiceQuestions } from '../../src/data/preparation-practice';
const route = 'nec/practice/';
const root = 'nec-practice';
test('keyboard answer, bookmark, filter and restart keep real local history', async ({ page }) => {
  await page.goto(route);
  const app = page.locator(root);
  await expect(app.locator('[data-interactive]')).toBeVisible();
  await app.getByRole('radio').first().focus();
  await page.keyboard.press('Space');
  await app.getByRole('button',{name:'Check answer',exact:true}).click();
  await expect(app.locator('[data-feedback]')).toContainText('Answer C is correct');
  await expect(app.locator('[data-performance] li').first()).toContainText('0/1 correct');
  await app.getByRole('button',{name:'Bookmark',exact:true}).click();
  await app.locator('[data-review]').selectOption('mistakes');
  await expect(app.locator('[data-position]')).toHaveText('Question 1 / 1');
  await app.getByRole('radio').nth(2).check();
  await app.getByRole('button',{name:'Check answer',exact:true}).click();
  await expect(app.locator('[data-performance] li').first()).toContainText('1/2 correct');
  await app.getByRole('button',{name:'Restart round',exact:true}).click();
  await expect(app.locator('[data-empty]')).toBeVisible();
  await app.locator('[data-review]').selectOption('bookmarks');
  await expect(app.locator('[data-position]')).toHaveText('Question 1 / 1');
  await page.reload();
  await expect(app.locator('[data-performance] li').first()).toContainText('1/2 correct');
  await expect(app.getByRole('button',{name:'Bookmarked ✓'})).toBeVisible();
});
test('practice timing starts on selection and expires without recording an unsubmitted answer', async ({ page }) => {
  await page.clock.install();
  await page.goto(route);
  const app = page.locator(root);
  await app.locator('[data-timing]').selectOption('5');
  await page.clock.fastForward(310_000);
  await expect(app.locator('[data-clock]')).toHaveText('Ready');
  await app.getByRole('radio').first().check();
  await page.clock.fastForward(300_000);
  await expect(app.locator('[data-status]')).toContainText('Practice time ended');
  await expect(app.getByRole('button',{name:'Check answer',exact:true})).toBeDisabled();
  await expect(app.locator('[data-total]')).toHaveText(`0 / ${practiceQuestions.length} seen`);
});
test('mobile controls fit and blocked storage still permits practice', async ({ page }) => {
  await page.setViewportSize({width:390,height:844});
  await page.addInitScript(() => Object.defineProperty(window,'localStorage',{get(){throw new Error('Storage blocked');}}));
  await page.goto(route);
  const app = page.locator(root);
  await expect(app.locator('[data-storage]')).toContainText('storage is unavailable');
  await app.getByRole('radio').nth(2).check();
  await app.getByRole('button',{name:'Check answer',exact:true}).click();
  await expect(app.locator('[data-feedback]')).toContainText('Correct.');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
});
test('all questions and explanations remain usable without JavaScript', async ({ browser, baseURL }) => {
  const context = await browser.newContext({javaScriptEnabled:false, baseURL});
  const page = await context.newPage();
  await page.goto(route);
  const bank = page.locator(`${root} [data-static]`);
  await expect(bank.locator('article')).toHaveCount(practiceQuestions.length);
  await bank.locator('summary').first().click();
  await expect(bank.locator('details').first()).toContainText('24 W');
  await context.close();
});

test('section and search filters combine, preserve bookmarks and clear from empty results', async ({ page }) => {
  await page.goto(route);
  const app = page.locator(root);
  await app.locator('[data-section]').selectOption('10.6');
  const sectionCount = practiceQuestions.filter(q => q.section === '10.6').length;
  await expect(app.locator('[data-position]')).toHaveText(`Question 1 / ${sectionCount}`);
  await expect(app.locator('[data-tag]')).toContainText('NEC 10.6');
  await app.getByRole('button',{name:'Bookmark',exact:true}).click();
  await app.locator('[data-review]').selectOption('bookmarks');
  await expect(app.locator('[data-position]')).toHaveText('Question 1 / 1');
  await app.locator('[data-search]').fill('STATUTORY');
  await expect(app.locator('[data-prompt]')).toContainText('statutory role');
  await app.locator('[data-subject]').selectOption('electrical');
  await expect(app.locator('[data-empty]')).toBeVisible();
  await app.getByRole('button',{name:'Show all questions',exact:true}).click();
  await expect(app.locator('[data-section]')).toHaveValue('all');
  await expect(app.locator('[data-search]')).toHaveValue('');
  await expect(app.locator('[data-position]')).toHaveText(`Question 1 / ${practiceQuestions.length}`);
  await app.locator('[data-search]').fill(' NEC 10.6 ');
  await expect(app.locator('[data-position]')).toHaveText(`Question 1 / ${sectionCount}`);
  await expect(app.getByRole('button',{name:'Bookmarked ✓'})).toBeVisible();
  await app.locator('[data-search]').fill('<img src=x onerror=alert(1)>');
  await expect(app.locator('[data-empty]')).toBeVisible();
  await expect(app.locator('img')).toHaveCount(0);
});
